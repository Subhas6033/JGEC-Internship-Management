import { Eye, Send } from "lucide-react";

import { Table } from "../../../../Components/index";
import NOCStatus from "./NOCStatus";

const NOCTable = ({ nocs, onView, onSend }) => {
  const columns = [
    {
      key: "student",
      header: "Student",
      render: (row) => (
        <div className="min-w-45">
          <p className="font-medium text-ink">{row.studentName}</p>

          <p className="mt-1 text-xs text-ink-muted">{row.rollNumber}</p>
        </div>
      ),
    },
    {
      key: "company",
      header: "Company",
      render: (row) => (
        <div className="min-w-37.5">
          <p className="text-sm font-medium text-ink">{row.company}</p>

          <p className="mt-1 text-xs text-ink-muted">{row.internshipRole}</p>
        </div>
      ),
    },
    {
      key: "department",
      header: "Department",
      render: (row) => (
        <span className="text-sm text-ink-muted">{row.department}</span>
      ),
    },
    {
      key: "generatedAt",
      header: "Generated On",
      render: (row) => (
        <span className="whitespace-nowrap text-sm text-ink">
          {row.generatedAt || "—"}
        </span>
      ),
    },
    {
      key: "status",
      header: "Dispatch Status",
      render: (row) => <NOCStatus status={row.status} />,
    },
    {
      key: "actions",
      header: "Actions",
      align: "right",
      render: (row) => (
        <div className="flex items-center justify-end gap-1">
          <button
            type="button"
            title="Preview NOC"
            onClick={() => onView(row)}
            className="rounded-lg p-2 text-ink-muted transition hover:bg-cream-soft hover:text-brand-600"
          >
            <Eye size={17} />
          </button>

          {row.status !== "Sent" && (
            <button
              type="button"
              title="Send NOC"
              onClick={() => onSend(row)}
              className="rounded-lg p-2 text-ink-muted transition hover:bg-green-50 hover:text-green-700"
            >
              <Send size={17} />
            </button>
          )}
        </div>
      ),
    },
  ];

  return (
    <Table
      columns={columns}
      data={nocs}
      getRowKey={(row) => row._id}
      emptyTitle="No generated NOCs found"
      emptyDescription="NOCs generated by department SPOCs will appear here."
    />
  );
};

export default NOCTable;
